def build(dbfile=DBFILE, apply=True):
    c = sqlite3.connect(dbfile)
    c.row_factory = sqlite3.Row
    base = c.execute("SELECT pokedex_no FROM pokemon_base ORDER BY pokedex_no").fetchall()
    nos = {r["pokedex_no"] for r in base}
    skill_ids = {r["skill_name"]: r["id"] for r in c.execute("SELECT id, skill_name FROM skill_base")}

    errs = []
    missing_pkm = sorted(nos - set(CURATED))
    if missing_pkm: errs.append(f"缺宝可梦: {missing_pkm}")
    for no, moves in sorted(CURATED.items()):
        if not (1 <= len(moves) <= 10): errs.append(f"{no} 招数 {len(moves)} 越界")
        prev = 0
        for lv, name in moves:
            nm = ALIAS.get(name, name)
            if nm not in skill_ids: errs.append(f"{no} 未知招式: {name}")
            if not (1 <= lv <= 50): errs.append(f"{no} 等级越界 {lv} ({name})")
            if lv < prev: errs.append(f"{no} 等级倒挂 {prev}→{lv} ({name})")
            prev = lv
        if moves and moves[0][0] != 1 and no not in EVOLVED_FORMS:
            errs.append(f"{no} 首招等级非1")
    assert not errs, "校验失败:\n" + "\n".join(errs[:60])

    # 别名归一后同（怪,招）去重，保留最早段位
    seen, rows = set(), []
    for no, moves in CURATED.items():
        for lv, name in moves:
            sid = skill_ids[ALIAS.get(name, name)]
            if (no, sid) in seen: continue
            seen.add((no, sid))
            rows.append((no, sid, lv))
    # 保证每只仍有 Lv1 招（去重极端情况下兜底：把最早招降为 Lv1）
    by_no = {}
    for no, sid, lv in rows:
        by_no.setdefault(no, []).append((lv, sid))
    fixed = []
    for no, lst in by_no.items():
        lst.sort()
        if lst and lst[0][0] != 1:
            lst[0] = (1, lst[0][1])
        for lv, sid in lst:
            fixed.append((no, sid, lv))
    c.execute("DELETE FROM pokemon_skill_learn")
    c.executemany("INSERT INTO pokemon_skill_learn(pokedex_no,skill_id,learn_level) VALUES(?,?,?)", fixed)
    # 清理孤儿招：冲浪/居合斩为秘传机招（原作升级不学，本作无地图剪枝玩法）→ 从技能库删除；
    # 防御性检查：仅当完全无人引用才删，避免误删在用招
    for ghost in ("冲浪", "居合斩"):
        used = c.execute("SELECT COUNT(*) FROM pokemon_skill_learn WHERE skill_id="
                         "(SELECT id FROM skill_base WHERE skill_name=?)", (ghost,)).fetchone()[0]
        if used == 0:
            c.execute("DELETE FROM skill_base WHERE skill_name=?", (ghost,))
    if apply:
        c.commit()
    c.close()
    return len(CURATED), len(fixed)


