def build_rows():
    # 1) 重复 key 检查（dict 天然去重会静默覆盖，显式拦截）
    seen = {}
    for pid, (reg, lo, hi, w, why) in PLOT_HOME.items():
        assert isinstance(reg, int) and 1 <= reg <= 8, f"非法区域 {pid}:{reg}"
        assert 1 <= lo <= hi <= 50, f"非法等级带 {pid}: Lv{lo}-{hi}"
        assert w >= 1, f"非法权重 {pid}:{w}"
        assert pid not in WILD_EXCLUDE, f"排除名单怪不应入表 {pid}"
        seen[pid] = reg
    assert len(seen) == len(PLOT_HOME), "PLOT_HOME 不应有重复 key"

    # 2) 终点形态检查（除雷丘特例外不得入池）；蛹检查
    c = sqlite3.connect(DBFILE)
    c.row_factory = sqlite3.Row
    fr = {r["from_no"] for r in c.execute("SELECT DISTINCT from_no FROM pkm_evolution")}
    to = {r["to_no"] for r in c.execute("SELECT DISTINCT to_no FROM pkm_evolution")}
    ends = to - fr
    bad_ends = sorted(p for p in PLOT_HOME if p in ends and p not in SPECIAL_EVOLVED_ALLOWED)
    assert not bad_ends, f"进化终点形态不应入野生池: {bad_ends}"
    assert not (set(PLOT_HOME) & {11, 14}), "蛹类(11/14)不得入野生池"

    rows = [(reg, pid, lo, hi, w) for pid, (reg, lo, hi, w, _why) in sorted(PLOT_HOME.items())]

    # 3) 难度阶梯断言：各区平均等级带中值单调不降
    per = defaultdict(list)
    for reg, pid, lo, hi, w in rows:
        per[reg].append((lo + hi) / 2)
    avgs = []
    for reg in sorted(REGIONS):
        assert per.get(reg), f"区{reg} 野生池为空"
        avgs.append(sum(per[reg]) / len(per[reg]))
    for i in range(1, len(avgs)):
        assert avgs[i] >= avgs[i - 1] - 1e-9, \
            f"难度倒挂：区{i} 均值{avgs[i-1]:.1f} > 区{i+1} 均值{avgs[i]:.1f}"
    # 4) v6 道馆锚定断言：每区 max_level ≤ 本区道馆推荐级 − 4
    GYM_REC = {1: 16, 2: 19, 3: 24, 4: 28, 5: 32, 6: 36, 7: 40, 8: 46}
    for reg, pid, lo, hi, w in rows:
        assert hi <= GYM_REC[reg] - 4, \
            f"v6 越带：区{reg} pid{pid} 上限Lv{hi} > 道馆推荐{GYM_REC[reg]}−4"
    c.close()
    return rows, avgs


def rebuild(apply=True):
    rows, avgs = build_rows()
    c = sqlite3.connect(DBFILE)
    if apply:
        c.execute("DELETE FROM region_base")
        c.executemany("INSERT INTO region_base(id, region_name, unlock_badge_count) VALUES(?,?,?)",
                      [(i, n, b) for i, (n, b) in REGIONS.items()])
        c.execute("DELETE FROM region_wild_pokemon")
        c.executemany("INSERT INTO region_wild_pokemon"
                      "(region_id,pokedex_no,min_level,max_level,catch_weight) VALUES(?,?,?,?,?)", rows)
        c.commit()
    # 汇报
    c.row_factory = sqlite3.Row
    dex = {r["pokedex_no"]: r["name"] for r in c.execute("SELECT pokedex_no,name FROM pokemon_base")}
    per = defaultdict(list)
    for reg, pid, lo, hi, w in rows:
        per[reg].append(pid)
    for reg in sorted(REGIONS):
        uniq = sorted(per.get(reg, []))
        avg = avgs[reg - 1]
        print(f"区{reg} {REGIONS[reg][0]}: {len(uniq)} 只 均值Lv{avg:.1f}  "
              f"样例 {[dex.get(p, p) for p in uniq[:6]]}")
    total = len({p for _, p, *_ in rows})
    print(f"合计野生可遇: {total} 种  条目: {len(rows)}  跨区重复: 0  "
          f"难度阶梯: {' → '.join(f'{a:.0f}' for a in avgs)}")
    c.close()
    return rows


