def build(dbfile=DBFILE, veekun=VEEKUN, apply=True):
    # 1) 身高体重：优先内嵌字典（离线可用），有 veekun-csv 则覆盖
    hw = dict(HW)
    pkm_csv = os.path.join(veekun, "pokemon.csv")
    if os.path.exists(pkm_csv):
        with open(pkm_csv, encoding="utf-8") as f:
            for row in csv.DictReader(f):
                if row.get("is_default") == "1":
                    hw[int(row["id"])] = (int(row["height"]) / 10.0, int(row["weight"]) / 10.0)

    # 2) 读本地 base（中文名/属性/基础值）
    c = sqlite3.connect(dbfile)
    c.row_factory = sqlite3.Row
    base = c.execute("SELECT pokedex_no,name,type1,type2,base_hp,base_atk,base_def,base_speed "
                     "FROM pokemon_base ORDER BY pokedex_no").fetchall()

    # 3) 完整性断言：CURATED 必须覆盖全部在册宝可梦，杜绝模板兜底文案回流
    nos = {r["pokedex_no"] for r in base}
    missing = sorted(nos - set(CURATED))
    assert not missing, f"CURATED 缺少 {len(missing)} 只: {missing}"
    for no, item in CURATED.items():
        assert isinstance(item, tuple) and len(item) == 2, f"{no} 条目格式异常"
        genus, intro = item
        assert genus and intro and len(intro) >= 15, f"{no} 档案不完整"
        assert "宝可梦" in genus, f"{no} 分类词异常: {genus}"
        assert "占位" not in intro and "mole" not in genus, f"{no} 存在未完成的占位文案"

    c.execute("DROP TABLE IF EXISTS pkm_profile")
    c.execute("""CREATE TABLE pkm_profile(
        pokedex_no INTEGER PRIMARY KEY, genus TEXT, height REAL, weight REAL, intro TEXT)""")

    n = 0
    for r in base:
        no = r["pokedex_no"]
        genus, intro = CURATED[no]
        h, w = hw.get(no, (None, None))
        c.execute("INSERT OR REPLACE INTO pkm_profile VALUES(?,?,?,?,?)",
                  (no, genus, h, w, intro))
        n += 1
    if apply:
        c.commit()
    c.close()
    return n


if __name__ == "__main__":
    n = build(apply=(os.environ.get("PKM_APPLY", "1") == "1"))
    print(f"档案生成完成：{n} 只")
